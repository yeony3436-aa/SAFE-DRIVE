"""Generate connected-grid return routes and an unsignalized turn route."""

import math
from pathlib import Path

import yaml


CONFIG = Path(__file__).resolve().parents[1] / 'config'
START = (-30.0, -1.75)


def arc(center, radius, start_angle, end_angle, segments=9):
    points = []
    for index in range(1, segments + 1):
        angle = start_angle + (end_angle - start_angle) * index / segments
        points.append((round(center[0] + radius * math.cos(angle), 3),
                       round(center[1] + radius * math.sin(angle), 3)))
    return points


def write_route(name, points, start=START, extra_parameters=None):
    # The controller tracks its next waypoint, not the nearest polyline point.
    # Dense straight samples keep the target local on long sides of the grid.
    dense_points = []
    previous = start
    for point in points:
        distance = math.dist(previous, point)
        steps = max(1, math.ceil(distance / 2.5))
        for index in range(1, steps + 1):
            fraction = index / steps
            dense_points.append((round(previous[0] + (point[0] - previous[0]) * fraction, 3),
                                 round(previous[1] + (point[1] - previous[1]) * fraction, 3)))
        previous = point
    points = dense_points
    cruise_speed = 1.2
    parameters = {
        'use_sim_time': True,
        'drive_mode': 'ackermann',
        'wheelbase': 2.5,
        'max_steer': 0.65,
        'target_speed': cruise_speed,
        'goal_tolerance': 0.7,
        'lookahead_distance': 1.5,
        'max_linear_speed': cruise_speed,
        'max_angular_speed': 0.8,
        'max_linear_deceleration': 0.8,
        'turn_speed': 0.0,
        'straight_tracking_enabled': False,
        'control_rate_hz': 20.0,
        'odom_timeout': 0.5,
        'waypoint_x': [x for x, _ in points],
        'waypoint_y': [y for _, y in points],
    }
    parameters.update(extra_parameters or {})
    path = CONFIG / f'connected_{name}.yaml'
    path.write_text('# Generated by scripts/generate_connected_routes.py.\n' +
                    yaml.safe_dump({'waypoint_follower': {'ros__parameters': parameters}},
                                   sort_keys=False))


def main():
    approach = [(-25.0, -1.75), (-15.0, -1.75), (-9.0, -1.75)]
    finish = [START]
    # Give the right loop a straight exit after its last bend so the chassis
    # can align with the eastbound lane before stopping at its start point.
    right_start = (-27.0, -1.75)
    right = approach + [(-3.75, -1.75)]
    right += arc((-3.75, -5.75), 4.0, math.pi / 2, 0)
    right += [(0.25, -20.0), (0.25, -40.0), (0.25, -50.25)]
    right += arc((-3.75, -50.25), 4.0, 0, -math.pi / 2)
    right += [(-15.0, -54.25), (-30.25, -54.25)]
    right += arc((-30.25, -50.25), 4.0, -math.pi / 2, -math.pi)
    right += [(-34.25, -35.0), (-34.25, -15.0), (-34.25, -5.75)]
    right += arc((-30.25, -5.75), 4.0, math.pi, math.pi / 2)
    right += [right_start]
    write_route('right_loop', right, start=right_start,
                extra_parameters={
                    'path_heading_gain': 1.0,
                    'max_lateral_acceleration': 0.36,
                    'max_steer': 0.70,
                })

    left = approach + [(-1.75, -1.75)]
    left += arc((-1.75, 3.75), 5.5, -math.pi / 2, 0)
    left += [(3.75, 20.0), (3.75, 40.0), (3.75, 50.25)]
    left += arc((-3.75, 50.25), 7.5, 0, math.pi / 2)
    left += [(-15.0, 57.75), (-30.25, 57.75)]
    left += arc((-30.25, 50.25), 7.5, math.pi / 2, math.pi)
    left += [(-37.75, 35.0), (-37.75, 20.0), (-37.75, 5.75)]
    left += arc((-30.25, 5.75), 7.5, math.pi, 3 * math.pi / 2)
    left += finish
    write_route('left_loop', left)

    straight = approach + [(-1.75, -1.75), (12.0, -1.75),
                           (25.0, -1.75), (30.25, -1.75)]
    straight += arc((30.25, 5.75), 7.5, -math.pi / 2, 0)
    straight += [(37.75, 25.0), (37.75, 50.25)]
    straight += arc((30.25, 50.25), 7.5, 0, math.pi / 2)
    straight += [(-10.0, 57.75), (-30.25, 57.75)]
    straight += arc((-30.25, 50.25), 7.5, math.pi / 2, math.pi)
    straight += [(-37.75, 30.0), (-37.75, 5.75)]
    straight += arc((-30.25, 5.75), 7.5, math.pi, 3 * math.pi / 2)
    straight += finish
    write_route('straight_loop', straight,
                extra_parameters={'max_lateral_acceleration': 0.45})

    outer_right = [(12.0, -1.75), (18.0, -1.75), (23.0, -1.75),
                   (29.65, -1.75)]
    outer_right += arc((29.65, -6.35), 4.6, math.pi / 2, 0)
    outer_right += [(34.25, -15.0), (34.25, -25.0), (34.25, -35.0)]
    write_route('unsignalized_right_turn', outer_right, start=(10.0, -1.75),
                extra_parameters={
                    'yield_enabled': True,
                    'yield_line_x': 22.75,
                    'yield_front_offset': 2.1,
                    'yield_line_margin': 1.2,
                    'yield_timeout': 1.0,
                    'yield_deceleration': 0.4,
                })


if __name__ == '__main__':
    main()
