#!/usr/bin/env python3
"""Generate the compact east-to-north bend used for steering validation."""

from math import cos, pi, sin
from pathlib import Path


OUTPUT = Path(__file__).resolve().parents[1] / 'worlds' / 'curve_course.world'
RADIUS = 12.0
SEGMENTS = 16
ROAD_WIDTH = 8.0
ARC_STEP = pi * RADIUS / (2.0 * SEGMENTS)


def box(name: str, x: float, y: float, yaw: float,
        length: float, width: float, z: float,
        color: str = '', collision: bool = False) -> str:
    kind = 'collision' if collision else 'visual'
    if color == 'asphalt':
        material = ('<material><script>'
                    '<uri>file://safe_drive_road/materials/scripts</uri>'
                    '<uri>file://safe_drive_road/materials/textures</uri>'
                    '<name>SafeDrive/Asphalt</name></script></material>')
    elif color:
        material = f'<material><ambient>{color}</ambient><diffuse>{color}</diffuse></material>'
    else:
        material = ''
    return (f'        <{kind} name="{name}"><pose>{x:.4f} {y:.4f} {z:.4f} 0 0 {yaw:.6f}</pose>'
            f'<geometry><box><size>{length:.4f} {width:.4f} 0.1</size></box></geometry>'
            f'{material}</{kind}>')


def main() -> None:
    white = '0.95 0.95 0.95 1'
    yellow = '0.95 0.85 0.10 1'
    pieces = []
    for name, x, y, yaw, length in (
        ('west', -20.0, 0.0, 0.0, 20.0),
        ('north', 2.0, 26.0, pi / 2.0, 28.0),
    ):
        pieces.append(box(f'{name}_collision', x, y, yaw, length, ROAD_WIDTH,
                          -0.05, collision=True))
        pieces.append(box(f'{name}_asphalt', x, y, yaw, length, ROAD_WIDTH,
                          -0.045, 'asphalt'))
        pieces.append(box(f'{name}_center', x, y, yaw, length, 0.12,
                          -0.035, yellow))
        for side in (-1, 1):
            edge_x = x - side * 3.75 * sin(yaw)
            edge_y = y + side * 3.75 * cos(yaw)
            pieces.append(box(f'{name}_edge_{side}', edge_x, edge_y, yaw,
                              length, 0.12, -0.034, white))
    for index in range(SEGMENTS):
        angle = (index + 0.5) * pi / (2.0 * SEGMENTS)
        x = -10.0 + RADIUS * sin(angle)
        y = 12.0 - RADIUS * cos(angle)
        length = ARC_STEP + 0.16
        prefix = f'bend_{index:02d}'
        pieces.append(box(f'{prefix}_collision', x, y, angle, length,
                          ROAD_WIDTH, -0.05, collision=True))
        pieces.append(box(f'{prefix}_asphalt', x, y, angle, length,
                          ROAD_WIDTH, -0.045, 'asphalt'))
        pieces.append(box(f'{prefix}_center', x, y, angle, length,
                          0.12, -0.035, yellow))
        for side in (-1, 1):
            edge_x = x - side * 3.75 * sin(angle)
            edge_y = y + side * 3.75 * cos(angle)
            pieces.append(box(f'{prefix}_edge_{side}', edge_x, edge_y, angle,
                              length, 0.12, -0.034, white))

    contents = '''<?xml version="1.0"?>
<!-- Generated by scripts/generate_curve_course.py; dimensions are metres. -->
<sdf version="1.6">
  <world name="safe_drive_curve_course">
    <physics name="ode" type="ode">
      <max_step_size>0.001</max_step_size>
      <real_time_factor>1.0</real_time_factor>
      <real_time_update_rate>1000</real_time_update_rate>
    </physics>
    <gravity>0 0 -9.81</gravity>
    <include><uri>model://ground_plane</uri><pose>0 0 -0.1 0 0 0</pose></include>
    <include><uri>model://sun</uri></include>
    <scene><ambient>0.45 0.45 0.45 1</ambient><background>0.7 0.85 1 1</background></scene>
    <model name="curve_road"><static>true</static><link name="surface">
''' + '\n'.join(pieces) + '''
    </link></model>
  </world>
</sdf>
'''
    OUTPUT.write_text(contents)


if __name__ == '__main__':
    main()
